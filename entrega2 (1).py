def segmentar_por_limiar(ndvi_imagem, limiares):
    """Segmenta a imagem NDVI por limiares."""
    segmentos = np.zeros_like(ndvi_imagem, dtype=np.uint8)
    for classe, limiar in limiares.items():
        if classe == 'água':
            segmentos[ndvi_imagem <= limiar] = 1
        elif classe == 'solo_nu':
            segmentos[(ndvi_imagem > limiares['água']) & (ndvi_imagem <= limiar)] = 2
        elif classe == 'veg_esparsa':
            segmentos[(ndvi_imagem > limiares['solo_nu']) & (ndvi_imagem <= limiar)] = 3
        elif classe == 'veg_densa':
            segmentos[ndvi_imagem > limiares['veg_esparsa']] = 4
    return segmentos

def segmentar_por_kmeans(imagem, k=5):
    """Segmenta a imagem usando K-means."""
    altura, largura = imagem.shape
    X = imagem.reshape(-1, 1)
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    labels = kmeans.fit_predict(X)
    return labels.reshape(altura, largura)

def segmentar_watershed(imagem):
    """Segmenta a imagem usando Watershed."""
    edges = filters.sobel(imagem)
    markers = np.zeros_like(imagem, dtype=np.int32)
    markers[imagem < 0.2] = 1
    markers[imagem > 0.6] = 2
    watershed_segments = segmentation.watershed(edges, markers)
    return watershed_segments

def extrair_estatisticas_por_segmento(imagem, segmentos):
    """Extrai estatísticas (média, desvio padrão) da imagem por segmento."""
    estatisticas = {}
    for i in np.unique(segmentos):
        if i != 0:  # Ignorar o fundo (se houver)
            mascara = segmentos == i
            estatisticas[i] = {
                'mean': np.mean(imagem[mascara]),
                'std': np.std(imagem[mascara])
            }
    return estatisticas

