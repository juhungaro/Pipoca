def calcular_ndvi_medio_anual(df):
    """Calcula o NDVI médio anual."""
    ndvi_medio_ano = (
        df.groupby('ano')['ndvi_media_mensal']
        .mean()
        .reset_index()
        .rename(columns={'ndvi_media_mensal': 'ndvi_medio_ano'})
    )
    return ndvi_medio_ano

def interpolar_dados_clima(df):
    """Interpola os dados climáticos."""
    if 'temperatura' in df.columns:
        df['temperatura'] = df['temperatura'].interpolate(method='linear', limit_direction='both')
        df['imputado_temp'] = df['temperatura'].isnull()
    if 'radiacao' in df.columns:
        df['radiacao'] = df['radiacao'].interpolate(method='linear', limit_direction='both')
        df['imputado_rad'] = df['radiacao'].isnull()
    return df

def imputar_clima_faltante(df, anos_faltantes, colunas_clima):
    """Imputa dados climáticos faltantes pela média dos outros anos."""
    for ano in anos_faltantes:
        for coluna in colunas_clima:
            df.loc[df['ano'] == ano, coluna] = df[df['ano'] != ano][coluna].mean()
    return df

